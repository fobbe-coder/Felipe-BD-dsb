CREATE DATABASE imobiliaria_ferrati;
USE imobiliaria_ferrati;

CREATE TABLE CLIENTE (
id_cliente INT AUTO_INCREMENT PRIMARY KEY,
nome VARCHAR(100) NOT NULL,
cpf VARCHAR(14) UNIQUE NOT NULL,
telefone VARCHAR(20),
email VARCHAR(100),
endereco VARCHAR(150),
status_inadimplencia BOOLEAN DEFAULT FALSE
);

CREATE TABLE PROPRIETARIO (
id_proprietario INT AUTO_INCREMENT PRIMARY KEY,
nome VARCHAR(100) NOT NULL,
cpf VARCHAR(14) UNIQUE NOT NULL,
telefone VARCHAR(20),
email VARCHAR(100),
endereco VARCHAR(150)
);

CREATE TABLE CORRETOR (
id_corretor INT AUTO_INCREMENT PRIMARY KEY,
nome VARCHAR(100) NOT NULL,
creci VARCHAR(20) UNIQUE,
telefone VARCHAR(20),
email VARCHAR(100)
);

CREATE TABLE IMOVEL (
id_imovel INT AUTO_INCREMENT PRIMARY KEY,
tipo_imovel VARCHAR(50),
endereco VARCHAR(150),
cidade VARCHAR(50),
estado VARCHAR(50),
valor_venda DECIMAL(12,2),
valor_aluguel DECIMAL(10,2),
status_imovel VARCHAR(30),
id_proprietario INT,
FOREIGN KEY (id_proprietario) REFERENCES PROPRIETARIO(id_proprietario)
);

CREATE TABLE VISITA (
id_visita INT AUTO_INCREMENT PRIMARY KEY,
data_visita DATE,
observacoes VARCHAR(200),
id_cliente INT,
id_imovel INT,
id_corretor INT,
FOREIGN KEY (id_cliente) REFERENCES CLIENTE(id_cliente),
FOREIGN KEY (id_imovel) REFERENCES IMOVEL(id_imovel),
FOREIGN KEY (id_corretor) REFERENCES CORRETOR(id_corretor)
);

CREATE TABLE CONTRATO (
id_contrato INT AUTO_INCREMENT PRIMARY KEY,
tipo_contrato VARCHAR(30),
data_inicio DATE,
data_fim DATE,
valor_contrato DECIMAL(10,2),
deposito DECIMAL(10,2),
status_contrato VARCHAR(30),
id_cliente INT,
id_imovel INT,
id_corretor INT,
FOREIGN KEY (id_cliente) REFERENCES CLIENTE(id_cliente),
FOREIGN KEY (id_imovel) REFERENCES IMOVEL(id_imovel),
FOREIGN KEY (id_corretor) REFERENCES CORRETOR(id_corretor)
);

CREATE TABLE PAGAMENTO (
id_pagamento INT AUTO_INCREMENT PRIMARY KEY,
data_pagamento DATE,
valor_pago DECIMAL(10,2),
forma_pagamento VARCHAR(30),
multa_atraso DECIMAL(10,2),
status_pagamento VARCHAR(30),
id_contrato INT,
FOREIGN KEY (id_contrato) REFERENCES CONTRATO(id_contrato)
);



